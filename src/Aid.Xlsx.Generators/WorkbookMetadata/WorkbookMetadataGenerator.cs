using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Aid.Xlsx.Generators.WorkbookMetadata;

[Generator(LanguageNames.CSharp)]
public sealed class WorkbookMetadataGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<INamedTypeSymbol?> types = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is ClassDeclarationSyntax { Identifier.ValueText: "XlsxProtectionAlgorithm" or "XlsxTableTheme" },
            static (syntax, cancellationToken) => syntax.SemanticModel.GetDeclaredSymbol(syntax.Node, cancellationToken) as INamedTypeSymbol);

        context.RegisterSourceOutput(types, static (output, type) =>
        {
            if (type?.ContainingAssembly.Name != "Aid.Xlsx")
                return;

            switch (type.ToDisplayString())
            {
                case "Aid.Xlsx.Model.Protection.XlsxProtectionAlgorithm":
                    EmitProtectionAlgorithms(output, type);
                    break;
                case "Aid.Xlsx.Model.Tables.XlsxTableTheme":
                    EmitTableThemes(output, type);
                    break;
            }
        });
    }

    private static void EmitProtectionAlgorithms(SourceProductionContext output, INamedTypeSymbol type)
    {
        (string Name, string Description)[] fields = [.. type.GetTypeMembers("Algorithm").Single().GetMembers().OfType<IFieldSymbol>()
            .Where(field => field.HasConstantValue)
            .Select(field => (field.Name, Description: SymbolDisplay.FormatLiteral(
                GetAttributeValue(field, "System.ComponentModel.DescriptionAttribute") ?? field.Name, quote: true)))];

        var source = new StringBuilder("""
            // <auto-generated/>
            #nullable enable

            namespace Aid.Xlsx.Model.Protection;

            public static partial class XlsxProtectionAlgorithm
            {
                internal static bool TryParseDescription(string description, out Algorithm algorithm)
                {
                    switch (description)
                    {

            """);
        foreach ((var name, var description) in fields)
            source.Append("            case ").Append(description).Append(": algorithm = Algorithm.").Append(name).AppendLine("; return true;");

        source.Append("""
                        default: algorithm = default; return false;
                    }
                }

                internal static string ToDescription(Algorithm algorithm) => algorithm switch
                {

            """);
        foreach ((var name, var description) in fields)
            source.Append("        Algorithm.").Append(name).Append(" => ").Append(description).AppendLine(",");

        source.Append("""
                    _ => throw new global::System.Collections.Generic.KeyNotFoundException(),
                };
            }

            """);
        output.AddSource("XlsxProtectionAlgorithm.g.cs", source.ToString().Replace("\r\n", "\n"));
    }

    private static string? GetAttributeValue(IFieldSymbol field, string attributeName) => field.GetAttributes()
        .FirstOrDefault(attribute => attribute.AttributeClass?.ToDisplayString() == attributeName)?
        .ConstructorArguments.FirstOrDefault().Value as string;

    private static void EmitTableThemes(SourceProductionContext output, INamedTypeSymbol type)
    {
        var source = new StringBuilder("""
            // <auto-generated/>
            #nullable enable

            namespace Aid.Xlsx.Model.Tables;

            public sealed partial class XlsxTableTheme
            {
                private static class BuiltInThemes
                {
                    internal static readonly global::System.Collections.Generic.IReadOnlyList<XlsxTableTheme> All =
                        global::System.Array.AsReadOnly(new XlsxTableTheme[]
                        {

            """);
        foreach (IFieldSymbol field in type.GetMembers().OfType<IFieldSymbol>())
        {
            if (field is { DeclaredAccessibility: Accessibility.Public, IsStatic: true, IsReadOnly: true }
                && SymbolEqualityComparer.Default.Equals(type, field.Type))
                source.Append("                ").Append(field.Name).AppendLine(",");
        }

        source.Append("""
                        });

                    internal static readonly global::System.Collections.Generic.Dictionary<string, XlsxTableTheme> ByName =
                        global::System.Linq.Enumerable.ToDictionary(All, theme => theme.Name, global::System.StringComparer.Ordinal);
                }
            }

            """);
        output.AddSource("XlsxTableTheme.g.cs", source.ToString().Replace("\r\n", "\n"));
    }
}
